package nl.stockio.logistics.mcp

import nl.stockio.logistics.domain.AllocationRequest
import nl.stockio.logistics.domain.BackorderFulfillmentRequest
import nl.stockio.logistics.domain.ExcelReportRequest
import nl.stockio.logistics.domain.ProcessDailyStockRequest
import nl.stockio.logistics.service.DailyStockLedgerService
import nl.stockio.logistics.service.ExcelReportGeneratorService
import nl.stockio.logistics.service.LogisticsAllocationService
import org.springframework.beans.factory.annotation.Value
import org.springframework.ai.tool.annotation.Tool
import org.springframework.stereotype.Component
import java.nio.file.Path

@Component
class LogisticsMcpTools(
    private val allocationService: LogisticsAllocationService,
    private val dailyStockLedgerService: DailyStockLedgerService,
    private val excelReportGenerator: ExcelReportGeneratorService,
    @param:Value("\${logistics.report.directory}")
    private val reportDirectory: String
) {

    @Tool(
        name = "calculate_allocation",
        description = "Allocate structured demand against inventory and inbound shipments. " +
            "Orders are processed by priority (lower number first), then FIFO. " +
            "Inbound shipments only cover orders when their expected arrival is on or before the required delivery date. " +
            "Any remainder is saved as an open backorder. Rebuild daily stock projections; allocated units leave physical stock on requiredDeliveryDate."
    )
    fun calculateAllocation(request: AllocationRequest) =
        allocationService.calculateAllocation(request)

    @Tool(
        name = "fulfill_open_backorders",
        description = "Use currently available inventory and shipments that have arrived by asOfDate " +
            "and whose expected arrival is on or before each order's required delivery date to fulfill persisted open backorders " +
            "in priority/FIFO order. Rebuild daily stock projections; allocated units leave physical stock on requiredDeliveryDate."
    )
    fun fulfillOpenBackorders(request: BackorderFulfillmentRequest) =
        allocationService.fulfillOpenBackorders(request)

    @Tool(
        name = "process_daily_stock",
        description = "Synchronize today's calculated stock_daily_snapshots closing balances to the live stock table. " +
            "The snapshot is generated by calculate_allocation; this tool does not recalculate allocation or accept stock movements."
    )
    fun processDailyStock(request: ProcessDailyStockRequest) =
        dailyStockLedgerService.process(request)

    @Tool(
        name = "generate_excel_report",
        description = "Generate an Excel workbook with allocation details, source allocations, native pivot tables, and formula-based SKU/status summaries for a saved allocation run. Use a simple .xlsx file name; by default, the workbook is written under ~/itzitzo-mcp/reports."
    )
    fun generateExcelReport(request: ExcelReportRequest): String {
        require(request.fileName.matches(Regex("[A-Za-z0-9][A-Za-z0-9._-]*\\.xlsx"))) {
            "fileName must be a simple .xlsx file name without a directory path."
        }
        val run = allocationService.getRun(request.runId)
        val path = excelReportGenerator.generate(run, Path.of(reportDirectory).resolve(request.fileName))
        return path.toString()
    }
}
